import "dotenv/config";
import express from "express";
import cors from "cors";
import helmet from "helmet";
import {rateLimit} from "express-rate-limit";
import briefRoutes from "./briefRoutes.js";
import organizationRoutes from "./organizationRoutes.js";
import marketplaceRoutes from "./marketplaceRoutes.js";
const app=express();
app.use(helmet());
const origins=(process.env.WIDGET_ALLOWED_ORIGINS??"http://localhost:5173").split(",").map(x=>x.trim()).filter(Boolean);
app.use(cors({origin:(origin,callback)=>!origin||origins.includes(origin)?callback(null,true):callback(new Error("Origin not allowed")),credentials:true}));
app.use(express.json({limit:"64kb"}));
app.use(rateLimit({windowMs:60000,limit:60,standardHeaders:true,legacyHeaders:false}));
app.get("/api/v1/health",(_req,res)=>res.json({status:"ok",service:"scopepilot-api",version:"v1"}));
app.use("/api/v1/briefs",briefRoutes);
app.use("/api/v1/organizations",organizationRoutes);
app.use("/api/v1/integrations",marketplaceRoutes);
app.use((err:unknown,_req:express.Request,res:express.Response,_next:express.NextFunction)=>{if(err instanceof Error&&err.message==="Origin not allowed")return res.status(403).json({error:{code:"ORIGIN_NOT_ALLOWED",message:"This origin is not allowed."}});console.error("unhandled_api_error",err instanceof Error?err.message:"unknown");return res.status(500).json({error:{code:"INTERNAL_ERROR",message:"An unexpected server error occurred."}});});
const port=Number(process.env.PORT??8787);
app.listen(port,()=>console.log("ScopePilot API listening on "+port));
